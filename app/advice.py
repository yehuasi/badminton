def generate_advice(shot_type, confidence, standardness, errors):
    """返回建议列表（中文字符串）。"""
    tips = []

    if confidence is not None and confidence < 0.5:
        tips.append("动作类型置信度偏低，请完整做完“引拍-击球-随挥”。")

    # 具体错误：优先输出前 3 条，并按规则权重顺序（ERROR_RULES 已按权重降序）。
    for err in errors or []:
        tips.append(ERROR_FIX.get(err, f"纠正：{err}"))

    if shot_type in SHOT_TIPS:
        tips.append(SHOT_TIPS[shot_type])

    if standardness is None:
        tips.append("暂未检测到完整动作，请全身入镜。")
    elif standardness >= 85:
        tips.append("标准度优秀，保持动作连贯性。")
    elif standardness >= 70:
        tips.append("标准度良好，注意上述细节可再提升。")
    elif standardness >= 55:
        tips.append("标准度一般，建议放慢动作对照要领练习。")
    else:
        tips.append("标准度偏低，建议先分解练习引拍与击球点。")

    return tips[:6]

